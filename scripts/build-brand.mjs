/**
 * Builds every file the product shows of the brand from the originals in brand/.
 *
 *   npm run brand                         writes the files and brand/outputs.json
 *   node scripts/build-brand.mjs --text   exits 1 if a text file differs from what a rebuild would write
 *
 * The originals (brand/*.svg, brand/*.png, brand/brand.json) are not drawn here: they came from the 0.3-D2 brand
 * source. This script only places them. Text outputs (SVG, logo.ts, the inline logo in site/index.html) are pure
 * functions of the originals, and tests/brand.test.ts compares them as text. Binary outputs need rsvg-convert, sips,
 * tiffutil and the Tauri CLI (macOS), and PNG bytes vary with the tool, so the committed files are the record:
 * brand/outputs.json stores the SHA-256 of each source and of each file written, and the test holds the two together.
 */
import {readFileSync, writeFileSync, copyFileSync, mkdtempSync, existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

export const ROOT = new URL('..', import.meta.url).pathname;
const read = p => readFileSync(join(ROOT, p), 'utf8');
export const sha = p => createHash('sha256').update(readFileSync(join(ROOT, p))).digest('hex');
const INK = JSON.parse(read('brand/brand.json')).colors.ink;

const attr = (svg, name) => svg.match(new RegExp('^<svg[^>]*\\s' + name + '="([^"]*)"'))?.[1];
const inner = svg => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const NS = 'xmlns="http://www.w3.org/2000/svg"';

/** The lockup with the word in the page ink, for files loaded through <img>, where currentColor would read as black. */
export function lockupInk() { return read('brand/lockup.svg').replaceAll('fill="currentColor"', 'fill="' + INK + '"'); }

export function logoTs() {
  const word = read('brand/wordmark.svg'), lock = read('brand/lockup.svg');
  const wordmark = '<svg ' + NS + ' viewBox="' + attr(word, 'viewBox') + '" fill="none" aria-hidden="true">' + inner(word) + '</svg>';
  const lockup = '<svg ' + NS + ' viewBox="' + attr(lock, 'viewBox') + '" fill="none" aria-hidden="true">' + inner(lock) + '</svg>';
  return [
    '// Generated by scripts/build-brand.mjs from brand/ (npm run brand). Do not edit by hand.',
    '/** "Aphrodite" in Wanted Sans 800, as outlines in currentColor, for lockups that supply their own mark. */',
    'export const brandWordmark=\x60' + wordmark + '\x60;',
    '',
    '/** Home lockup: the symbol (public/brand/apple-mark.png, a render of brand/symbol-gold.svg) beside the wordmark. */',
    'export const appLockup=\x60<img class="brand-app-icon" src="/brand/apple-mark.png" width="40" height="40" alt="" draggable="false">$\x7bbrandWordmark}\x60;',
    '',
    '/** The horizontal lockup: gold symbol and outlined wordmark in currentColor. Vector, no font. */',
    'export const brandLockup=\x60' + lockup + '\x60;',
    '',
  ].join('\n');
}

/** site/index.html with the inline logo inside <a class="lockup"> replaced; the surrounding markup is left as it is. */
export function siteIndex() {
  const lock = read('brand/lockup.svg');
  const next = '<svg viewBox="' + attr(lock, 'viewBox') + '" fill="none" aria-hidden="true">' + inner(lock) + '</svg>';
  const html = read('site/index.html');
  const re = /(<a class="lockup"[^>]*>\s*)<svg[\s\S]*?<\/svg>/;
  if (!re.test(html)) throw new Error('site/index.html has no <a class="lockup"> with an inline svg');
  return html.replace(re, (_, head) => head + next);
}

/** Every text file written, by repo path. */
export function textOutputs() {
  return {
    'src/design/logo.ts': logoTs(),
    'public/brand/apple-a-lockup.svg': lockupInk(),
    'site/assets/brand/apple-a-lockup.svg': lockupInk(),
    'public/icon.svg': read('brand/favicon.svg'),
    'site/assets/brand/favicon.svg': read('brand/favicon.svg'),
    'site/index.html': siteIndex(),
  };
}

/** Binary files copied as they are: [from, to]. */
export const COPIES = [
  ['brand/app-icon-1024.png', 'public/brand/app-icon-1024.png'],
  ['brand/favicon-16.png', 'site/assets/brand/favicon-16.png'],
  ['brand/favicon-32.png', 'site/assets/brand/favicon-32.png'],
  ['brand/apple-touch-icon-180.png', 'site/assets/brand/apple-touch-icon-180.png'],
  ...['128x128.png', '128x128@2x.png', '32x32.png', '64x64.png', 'Square107x107Logo.png', 'Square142x142Logo.png',
    'Square150x150Logo.png', 'Square284x284Logo.png', 'Square30x30Logo.png', 'Square310x310Logo.png',
    'Square44x44Logo.png', 'Square71x71Logo.png', 'Square89x89Logo.png', 'StoreLogo.png', 'icon.png']
    .map(n => ['brand/icons/' + n, 'src-tauri/icons/' + n]),
];

function run(cmd, args) {
  const r = spawnSync(cmd, args, {encoding: 'utf8'});
  if (r.error?.code === 'ENOENT') throw new Error(cmd + ' is not installed; npm run brand needs rsvg-convert (brew install librsvg), sips, tiffutil and the Tauri CLI on macOS');
  if (r.status !== 0) throw new Error(cmd + ' ' + args.join(' ') + ' failed\n' + r.stdout + r.stderr);
}

// Where the lockup goes on the 1320 x 800 background: the symbol's left edge at x, the lockup's top at y, scaled by s.
const DMG = {x: 66, y: 50.2, s: 1.55};
/** The DMG background: the logo-less base from brand/dmg with the lockup drawn where the old mark and wordmark were. */
function dmgSvg() {
  const base = readFileSync(join(ROOT, 'brand/dmg/background-base@2x.png')).toString('base64');
  const symbolLeft = JSON.parse(read('brand/brand.json')).symbol.bbox[0];
  return '<svg ' + NS + ' xmlns:xlink="http://www.w3.org/1999/xlink" width="1320" height="800" viewBox="0 0 1320 800">'
    + '<image width="1320" height="800" xlink:href="data:image/png;base64,' + base + '"/>'
    + '<g transform="translate(' + (DMG.x - symbolLeft * DMG.s) + ' ' + DMG.y + ') scale(' + DMG.s + ')">' + inner(lockupInk()) + '</g></svg>';
}

function pngSize(p) {
  const b = readFileSync(join(ROOT, p));
  return [b.readUInt32BE(16), b.readUInt32BE(20)];
}

export function build() {
  for (const [p, text] of Object.entries(textOutputs())) writeFileSync(join(ROOT, p), text);
  for (const [from, to] of COPIES) copyFileSync(join(ROOT, from), join(ROOT, to));
  const scratch = mkdtempSync(join(tmpdir(), 'aphrodite-brand-'));
  // The mark in the left panel and the Home sidebar: the gold symbol, 256 px square, transparent.
  run('rsvg-convert', ['-w', '256', '-h', '256', join(ROOT, 'brand/symbol-gold.svg'), '-o', join(ROOT, 'public/brand/apple-mark.png')]);
  // The site's app icon: the app icon at 256 px, with its own corners and shadow.
  run('sips', ['-z', '256', '256', join(ROOT, 'brand/app-icon-1024.png'), '--out', join(ROOT, 'site/assets/brand/app-icon.png')]);
  // icon.icns and icon.ico come from the Tauri CLI. Its PNGs are not used (brand/icons are), and ios and android stay as they are.
  run(join(ROOT, 'node_modules/.bin/tauri'), ['icon', join(ROOT, 'brand/app-icon-1024.png'), '-o', scratch]);
  for (const n of ['icon.icns', 'icon.ico']) copyFileSync(join(scratch, n), join(ROOT, 'src-tauri/icons', n));
  // DMG background: 1x and 2x drawn from one SVG, then joined into the TIFF macOS picks from by screen.
  const svg = join(scratch, 'dmg.svg');
  writeFileSync(svg, dmgSvg());
  run('rsvg-convert', ['-w', '1320', '-h', '800', svg, '-o', join(ROOT, 'src-tauri/dmg/background@2x.png')]);
  run('rsvg-convert', ['-w', '660', '-h', '400', svg, '-o', join(ROOT, 'src-tauri/dmg/background.png')]);
  run('tiffutil', ['-cathidpicheck', join(ROOT, 'src-tauri/dmg/background.png'), join(ROOT, 'src-tauri/dmg/background@2x.png'), '-out', join(ROOT, 'src-tauri/dmg/background.tiff')]);

  const dmgFrom = ['brand/dmg/background-base@2x.png', 'brand/lockup.svg'];
  const rows = [
    ['public/brand/apple-mark.png', ['brand/symbol-gold.svg']],
    ['site/assets/brand/app-icon.png', ['brand/app-icon-1024.png']],
    ['src-tauri/icons/icon.icns', ['brand/app-icon-1024.png']],
    ['src-tauri/icons/icon.ico', ['brand/app-icon-1024.png']],
    ['src-tauri/dmg/background.png', dmgFrom],
    ['src-tauri/dmg/background@2x.png', dmgFrom],
    ['src-tauri/dmg/background.tiff', dmgFrom],
    ...COPIES.map(([from, to]) => [to, [from]]),
  ];
  const outputs = {};
  for (const [to, from] of rows) {
    const o = {from: Object.fromEntries(from.map(f => [f, sha(f)])), sha256: sha(to)};
    if (to.endsWith('.png')) o.size = pngSize(to);
    outputs[to] = o;
  }
  writeFileSync(join(ROOT, 'brand/outputs.json'), JSON.stringify(outputs, null, 1) + '\n');
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  if (process.argv.includes('--text')) {
    const stale = Object.entries(textOutputs()).filter(([p, t]) => !existsSync(join(ROOT, p)) || read(p) !== t).map(([p]) => p);
    if (stale.length) { console.error('stale: ' + stale.join(', ')); process.exit(1); }
  } else { build(); console.log('brand files written; brand/outputs.json updated'); }
}

/** Rows by id. */
export const commandById = Object.fromEntries(commands.map(row => [row.id, row]));
/**
 * The row only the person may do that a screen action belongs to, outside the interface around the design
 * (chrome rows are the person's too, and an agent may still act them): an agent's act, click or palette
 * command that would reach one is refused before it runs (0.3-P3-fix1).
 */
export function personOnlyRow(actionName) {
  if (typeof actionName !== 'string') return undefined;
  const name = actionName.trim().toLowerCase();
  return commands.find(row => row.author === 'person-only' && row.grade !== 'chrome' && row.controls.some(c => c.kind === 'action' && c.name === name))?.id;
}

/** The grade the permission rule judges a gate kind by, or undefined for a kind no row has. */
export function gradeOfKind(kind) {
  return commands.find(row => row.kind === kind)?.grade;
}

/** Every gate kind with the given grades, in table order, each once. */
export function kindsOfGrade(...wanted) {
  return [...new Set(commands.filter(row => row.kind && wanted.includes(row.grade)).map(row => row.kind))];
}

/** The loopback routes as the bridge advertises them: `METHOD /path`, in table order, each once. */
export function loopbackRoutes() {
  return [...new Set(commands.filter(row => row.surfaces.loopback && row.route).map(row => `${row.route.method} ${row.route.path}`))];
}

/** One row as an MCP tool, in the shape mcp/aphrodite-mcp/tools.mjs exports. */
export function toTool(row) {
  const {name, title, description, annotations, params, body} = row.mcp;
  return {name, title, description, annotations, inputSchema: row.input, route: row.route, ...(params ? {params} : {}), ...(body ? {body} : {})};
}

/** The MCP tool list, in the order a client is shown it. */
export function mcpTools() {
  return commands.filter(row => row.surfaces.mcp && row.mcp).sort((a, b) => a.mcp.order - b.mcp.order).map(toTool);
}
